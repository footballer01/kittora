// Runs before `next build` (see package.json "build").
//
// 1. Writes public/_redirects (and _headers) from scripts/import/redirects.json, so v1's
//    /product/<id> links 301 to the new product pages (Cloudflare static assets).
// 2. With NEXT_PUBLIC_SUPABASE_URL + ANON_KEY set: reads the published catalogue
//    with the anon key (RLS applies, exactly what a shopper may see), copies every
//    image and video into public/media/ and writes .catalog/snapshot.json.
//    Without them: removes any old snapshot so the build uses the v1 import.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createClient } from "@supabase/supabase-js";
import { config } from "dotenv";
import { EDIT_SELECT, PRODUCT_SELECT, editFromDb, mediaObjects, productFromDb, type DbEdit, type DbProduct } from "@/lib/catalog/from-db";
import { SNAPSHOT_FILE, type Snapshot } from "@/lib/catalog/source";

config({ path: ".env.local", quiet: true });

const root = process.cwd();
const MEDIA_DIR = join(root, "public/media");
const CONCURRENCY = 6;

function writeRedirects() {
  const map = JSON.parse(readFileSync(join(root, "scripts/import/redirects.json"), "utf8")) as Record<string, { from: string; slug: string }>;
  const lines = Object.values(map).map((r) => `${r.from} /product/${r.slug} 301`);
  writeFileSync(join(root, "public/_redirects"), `# Generated by scripts/catalog/snapshot.ts — v1 product links\n${lines.join("\n")}\n`);
  console.log(`  ${lines.length} v1 redirects`);
  // The share image is exported without an extension; tell Cloudflare it's a PNG.
  writeFileSync(join(root, "public/_headers"), "/opengraph-image\n  Content-Type: image/png\n");
}

async function download(base: string, objects: [string, string][]) {
  let next = 0;
  const worker = async () => {
    while (next < objects.length) {
      const [bucket, path] = objects[next++];
      const out = join(MEDIA_DIR, path);
      const res = await fetch(`${base}/storage/v1/object/public/${bucket}/${path.split("/").map(encodeURIComponent).join("/")}`);
      if (!res.ok) throw new Error(`Download ${bucket}/${path}: HTTP ${res.status}`);
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, Buffer.from(await res.arrayBuffer()));
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
}

async function main() {
  console.log("Catalogue snapshot");
  writeRedirects();

  const url = process.env.NEXT_PUBLIC_SUPABASE_URL?.trim();
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY?.trim();
  if (!url || !key) {
    rmSync(SNAPSHOT_FILE, { force: true });
    console.log("  Supabase not configured: building from the v1 import");
    return;
  }

  const db = createClient(url, key, { auth: { persistSession: false } });
  const products = await db.from("products").select(PRODUCT_SELECT).eq("published", true).order("created_at");
  if (products.error) throw new Error(`products: ${products.error.message}`);
  const edits = await db.from("edits").select(EDIT_SELECT).eq("published", true).order("position");
  if (edits.error) throw new Error(`edits: ${edits.error.message}`);

  const rows = products.data as unknown as DbProduct[];
  const objects = [...new Map(mediaObjects(rows).map((o) => [o.join("/"), o])).values()];
  rmSync(MEDIA_DIR, { recursive: true, force: true });
  await download(url, objects);

  const catalog = rows.map(productFromDb);
  const ids = new Set(catalog.map((p) => p.id));
  const snapshot: Snapshot = {
    source: "supabase",
    builtAt: new Date().toISOString(),
    products: catalog,
    edits: (edits.data as unknown as DbEdit[]).map((e) => editFromDb(e, ids)).filter((e) => e.productIds.length > 0),
  };
  mkdirSync(dirname(SNAPSHOT_FILE), { recursive: true });
  writeFileSync(SNAPSHOT_FILE, JSON.stringify(snapshot));
  console.log(`  ${catalog.length} products, ${snapshot.edits.length} edits, ${objects.length} media files copied`);
}

main().catch((err) => {
  console.error(`✗ ${(err as Error).message}`);
  process.exit(1);
});
