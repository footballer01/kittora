// Writes styles/tokens.css from scripts/import/tokens.proposal.json (the
// accepted Phase 0.5 proposal). Re-run after changing the proposal:
//   npm run tokens
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Token = { value: string; usage: string };
const proposal = JSON.parse(readFileSync(join(process.cwd(), "scripts/import/tokens.proposal.json"), "utf8")) as {
  themes: { dark: Record<string, Token>; light: Record<string, Token> };
  typeScale: { base: number; ratio: number; steps: Record<string, { px: number }> };
};

const block = (t: Record<string, Token>) =>
  Object.entries(t)
    .map(([k, v]) => `  ${k}: ${v.value}; /* ${v.usage} */`)
    .join("\n");

const rem = (px: number) => `${+(px / 16).toFixed(4)}rem`;
const steps = Object.entries(proposal.typeScale.steps)
  .sort((a, b) => Number(a[0]) - Number(b[0]))
  .map(([n, s]) => `  --step-${n.replace("-", "n")}: ${rem(Math.max(12, s.px))};`)
  .join("\n");

const css = `/* Generated by scripts/build-tokens.ts from scripts/import/tokens.proposal.json. Do not edit by hand. */

/* Dark is v1's theme and the default. */
:root,
[data-theme="dark"] {
${block(proposal.themes.dark)}
  color-scheme: dark;
}

/* Light variant, derived from v1's light footer. */
[data-theme="light"] {
${block(proposal.themes.light)}
  color-scheme: light;
}

/* Type scale: ${proposal.typeScale.base}px base, ${proposal.typeScale.ratio} ratio (floor 12px). */
:root {
${steps}
  --radius-input: 0.75rem;
  --radius-card: 1rem;
  --radius-pill: 9999px;
}
`;
writeFileSync(join(process.cwd(), "styles/tokens.css"), css);
console.log("Wrote styles/tokens.css");
